/**
 * externalIdeas.ts — telemetry-sourced tool ideas from fleet partners (SIEVE),
 * pure from the HTTP surface and from the forge.
 *
 * WHY THIS EXISTS (measured 2026-10-12): the forge agenda is a static list of
 * ~2,200 specs plus dream-gene and learner-mint sources. Nothing about what is
 * happening TODAY — Sieve's live telemetry (hot 5xx routes, latent slow
 * routes, oscillating tests) — could reach the forge, so the "telemetry
 * actionable" loop was stuck at a dashboard. This module is the honest bridge:
 * fleet partners POST validated idea cards; each card must carry its own
 * behavioral contract (a refSuite the forge can judge) so a generated tool is
 * still gated exactly like any other capability.
 *
 * Pure functions only — the route and runForgeCycle own I/O and state.
 */
import type { ToolDomain } from '../types.js';

export interface ExternalIdeaCard {
  /** Stable id from the source (e.g. `sieve:idea:<slug>`). Dedupe key. */
  id: string;
  /** Source system slug (e.g. 'sieve'). */
  source?: string;
  domain: ToolDomain;
  /** Exact exported function name the generated tool must define. */
  toolName: string;
  title: string;
  /** The actionable text: what telemetry saw, what the tool must do. */
  prompt: string;
  /** Hidden reference suite — asserts, one per behavior the tool must have. */
  refSuite: string;
  /** 0..1 urgency as measured by the source's own scoring. */
  score?: number;
  /** Anchor evidence from the source (shown in dashboards, not to the model). */
  evidence?: Record<string, unknown>;
  createdAt?: number;
  /**
   * 'tool' (default) is a micro-tool generated by the forge against refSuite.
   * 'scaffold' is a FULL-STACK artifact built deterministically by the factory
   * (Cheetah 4 via SIEVE) — no model, no refSuite; `scaffold` describes what to
   * build. This is the difference between a function and a feature.
   */
  kind?: 'tool' | 'scaffold';
  scaffold?: {
    /** factory kind: component | hook | context | page | service | feature | project | batch | doc */
    factoryKind: string;
    name?: string;
    recipe?: string;
    fields?: string;
    spec?: string;
    cwd?: string;
    args?: string[];
  };
}

export interface ExternalStateIdea extends ExternalIdeaCard {
  status: 'pending' | 'built' | 'failed' | 'quarantined';
  /** The ForgeSpec id when dispatched to the forge (`ext_<cardIdSlug>`). */
  specId?: string;
  builtTool?: string;
  builtVersionHash?: string;
  failureReason?: string;
  quarantinedAt?: number;
  builtAt?: number;
  /** Re-posts after a failure (a source can fix its own fixture). Capped. */
  retries?: number;
}

const MAX_IDEAS = 64;
/** A source may revise its own contract after a failure this many times. */
const MAX_IDEA_RETRIES = 3;

export interface IngestResult {
  accepted: ExternalIdeaCard[];
  rejected: Array<{ id?: string; reason: string }>;
}

const VALID_DOMAINS: ReadonlySet<string> = new Set([
  'coding', 'math', 'biotech', 'systemic', 'neuro_symbolic', 'cyber_defense', 'quantum_sim',
]);

const SAFE_NAME = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
/** Factory kinds a scaffold card may request (mirrors factory.ts's catalogue). */
const SCAFFOLD_KINDS = new Set([
  'project', 'component', 'hook', 'context', 'page', 'service', 'feature', 'batch', 'doc',
]);

function slugOf(id: unknown): string {
  return String(id ?? '').replace(/[^a-zA-Z0-9_]/g, '_').slice(0, 80);
}

/** Deterministic ForgeSpec id for a card (stable, collision-free up to cap). */
export function ideaSpecId(card: ExternalIdeaCard): string {
  return `ext_${slugOf(card.id)}`;
}

/** One card in, validation verdict out. Refusals name their reason. */
export function validateIdea(raw: unknown): { ok: true; card: ExternalIdeaCard } | { ok: false; id?: string; reason: string } {
  if (!raw || typeof raw !== 'object') return { ok: false, reason: 'not an object' };
  const r = raw as Record<string, unknown>;
  const id = typeof r.id === 'string' ? r.id.trim() : '';
  if (id.length < 4 || id.length > 96) return { ok: false, id, reason: 'id is required (4..96 chars)' };

  const kind = r.kind === 'scaffold' ? 'scaffold' : 'tool';

  if (kind === 'scaffold') {
    // A scaffold card is DETERMINISTIC: it names what to build, not how to
    // verify a model's code. Requiring a refSuite here would be wrong; requiring
    // a valid factoryKind is not.
    const s = (r.scaffold ?? {}) as Record<string, unknown>;
    const factoryKind = typeof s.factoryKind === 'string' ? s.factoryKind.trim() : '';
    if (!SCAFFOLD_KINDS.has(factoryKind)) {
      return { ok: false, id, reason: `scaffold.factoryKind must be one of ${[...SCAFFOLD_KINDS].join(', ')}` };
    }
    const title = typeof r.title === 'string' ? r.title.trim() : '';
    if (title.length < 8 || title.length > 160) return { ok: false, id, reason: 'title is required (8..160 chars)' };
    const card: ExternalIdeaCard = {
      id,
      source: typeof r.source === 'string' ? r.source.slice(0, 40) : undefined,
      domain: (typeof r.domain === 'string' ? r.domain : 'coding') as ToolDomain,
      toolName: typeof r.toolName === 'string' && SAFE_NAME.test(r.toolName) ? r.toolName : `scaffold_${factoryKind}`,
      title,
      prompt: typeof r.prompt === 'string' ? r.prompt.slice(0, 4000) : title,
      refSuite: '',
      kind: 'scaffold',
      scaffold: {
        factoryKind,
        ...(typeof s.name === 'string' ? { name: s.name } : {}),
        ...(typeof s.recipe === 'string' ? { recipe: s.recipe } : {}),
        ...(typeof s.fields === 'string' ? { fields: s.fields } : {}),
        ...(typeof s.spec === 'string' ? { spec: s.spec } : {}),
        ...(typeof s.cwd === 'string' ? { cwd: s.cwd } : {}),
        ...(Array.isArray(s.args) ? { args: s.args.filter((a) => typeof a === 'string').slice(0, 16) as string[] } : {}),
      },
      ...(typeof r.score === 'number' && Number.isFinite(r.score) ? { score: Math.max(0, Math.min(1, r.score)) } : {}),
      createdAt: typeof r.createdAt === 'number' ? r.createdAt : Date.now(),
    };
    return { ok: true, card };
  }

  if (typeof r.toolName !== 'string' || !SAFE_NAME.test(r.toolName) || r.toolName.length > 48) {
    return { ok: false, id, reason: `toolName must be a valid identifier (<=48 chars)` };
  }
  if (!VALID_DOMAINS.has(String(r.domain))) {
    return { ok: false, id, reason: `domain "${String(r.domain)}" is not a recognized ToolDomain` };
  }
  const title = typeof r.title === 'string' ? r.title.trim() : '';
  if (title.length < 8 || title.length > 160) return { ok: false, id, reason: 'title is required (8..160 chars)' };
  const prompt = typeof r.prompt === 'string' ? r.prompt.trim() : '';
  if (prompt.length < 40 || prompt.length > 4000) return { ok: false, id, reason: 'prompt is required (40..4000 chars) — it is the model-visible contract' };
  const refSuite = typeof r.refSuite === 'string' ? r.refSuite.trim() : '';
  const asserts = refSuite.match(/\bassert\b/g)?.length ?? 0;
  if (asserts < 2) return { ok: false, id, reason: 'refSuite with >=2 asserts is required — a tool idea without a testable contract is not forgeable' };
  if (refSuite.length > 4000) return { ok: false, id, reason: 'refSuite too large (>4000 chars)' };
  const score = typeof r.score === 'number' && Number.isFinite(r.score) ? Math.max(0, Math.min(1, r.score)) : undefined;
  const card: ExternalIdeaCard = {
    id,
    source: typeof r.source === 'string' ? r.source.slice(0, 40) : undefined,
    domain: String(r.domain) as ToolDomain,
    toolName: r.toolName,
    title,
    prompt,
    refSuite,
    ...(score !== undefined ? { score } : {}),
    ...(r.evidence && typeof r.evidence === 'object' && !Array.isArray(r.evidence)
      ? { evidence: JSON.parse(JSON.stringify(r.evidence)) as Record<string, unknown> }
      : {}),
    ...(typeof r.createdAt === 'number' ? { createdAt: r.createdAt } : { createdAt: Date.now() }),
  };
  return { ok: true, card };
}

/** One shot: validate a batch, reject duplicates (by id, incl. history since the store keeps statuses), enforce the cap. */
export function ingestIdeas(
  incoming: unknown[],
  existing: ExternalStateIdea[],
  now: number = Date.now(),
): IngestResult {
  const out: IngestResult = { accepted: [], rejected: [] };
  const seen = new Set(existing.map((e) => e.id));
  const counts = new Map<string, number>();
  for (const e of existing) {
    if (e.status === 'failed') counts.set(e.id, (counts.get(e.id) ?? 0) + 1); // failed attempts are retryable, not blockers
  }
  for (const raw of incoming) {
    const v = validateIdea(raw);
    if (!v.ok) { out.rejected.push({ id: v.id, reason: v.reason }); continue; }
    const card = v.card;
    if (seen.has(card.id)) {
      const prior = existing.find((e) => e.id === card.id)!;
      // A still-pending card is REFRESHED (fresher score/evidence, same ask).
      if (prior.status === 'pending') {
        prior.prompt = card.prompt;
        prior.refSuite = card.refSuite;
        prior.score = card.score ?? prior.score;
        prior.evidence = card.evidence ?? prior.evidence;
        out.accepted.push(card);
        continue;
      }
      // A FAILED card is RETRYABLE while its retry budget lasts: the source may
      // have fixed its own acceptance fixture (measured 2026-10-12 — a bad
      // refSuite failed the forge and the card could not be corrected). The
      // revised contract replaces the old one and the card returns to pending.
      if (prior.status === 'failed' && (prior.retries ?? 0) < MAX_IDEA_RETRIES) {
        prior.prompt = card.prompt;
        prior.refSuite = card.refSuite;
        prior.score = card.score ?? prior.score;
        prior.evidence = card.evidence ?? prior.evidence;
        prior.status = 'pending';
        prior.retries = (prior.retries ?? 0) + 1;
        delete prior.failureReason;
        out.accepted.push(card);
        continue;
      }
      out.rejected.push({ id: card.id, reason: `duplicate id (status ${prior.status})` });
      seen.add(card.id);
      continue;
    }
    const failedBefore = counts.get(card.id) ?? 0;
    if (failedBefore >= 3) { out.rejected.push({ id: card.id, reason: 'failed 3+ prior attempts (re-post needs a materially new id)' }); continue; }
    if (seen.size >= MAX_IDEAS) { out.rejected.push({ id: card.id, reason: `store full (${MAX_IDEAS} cards)` }); continue; }
    seen.add(card.id);
    card.createdAt = card.createdAt ?? now;
    existing.push({ ...card, status: 'pending', specId: ideaSpecId(card) });
    out.accepted.push(card);
  }
  return out;
}

export interface PickContext {
  /** Tool names already materialized by the forge (ledger + registry + selfhost). */
  built: ReadonlySet<string>;
  /** Quarantine map name -> count; a spec restarts after FORGE_QUARANTINE_LIMIT. */
  quarantine?: Map<string, number>;
  quarantineLimit?: number;
  limit?: number;
}

/** Cards eligible for the forge: pending, not built under their toolName, not quarantined. Best score first. */
export function pickIdeasForForge(
  existing: ExternalStateIdea[],
  ctx: PickContext,
): ExternalStateIdea[] {
  const qLimit = ctx.quarantineLimit ?? 1;
  return existing
    .filter((idea) => {
      if (idea.status !== 'pending') return false;
      if (idea.kind === 'scaffold') return false; // scaffold cards go to the FACTORY, not the forge
      if (ctx.built.has(idea.toolName)) return false;
      const q = ctx.quarantine?.get(idea.toolName) ?? ctx.quarantine?.get(ideaSpecId(idea)) ?? 0;
      return q < qLimit;
    })
    .sort((a, b) => (b.score ?? 0.5) - (a.score ?? 0.5))
    .slice(0, ctx.limit ?? 3);
}

/** Pending FULL-STACK cards for the deterministic factory lane (no model). */
export function pickScaffoldIdeas(
  existing: ExternalStateIdea[],
  opts: { limit?: number } = {},
): ExternalStateIdea[] {
  return existing
    .filter((idea) => idea.status === 'pending' && idea.kind === 'scaffold' && idea.scaffold)
    .sort((a, b) => (b.score ?? 0.5) - (a.score ?? 0.5))
    .slice(0, opts.limit ?? 1);
}

/** Build one ForgeSpec from a card. Pure — the caller owns dispatch + bookkeeping. */
export function specFromIdea(idea: ExternalStateIdea): {
  id: string; name: string; domain: ExternalIdeaCard['domain']; title: string;
  prompt: string; refSuite: string; externalIdeaId: string;
} {
  return {
    id: idea.specId ?? ideaSpecId(idea),
    name: idea.toolName,
    domain: idea.domain,
    title: idea.title,
    // The model sees the operator's own evidence: what telemetry saw and what
    // the tool must do. The refSuite stays hidden (the real judge).
    prompt: idea.prompt,
    refSuite: idea.refSuite,
    externalIdeaId: idea.id,
  };
}

/** Mark one card with an outcome. Returns false when the id is unknown (never guessed). */
export function markIdeaOutcome(
  existing: ExternalStateIdea[],
  id: string,
  outcome: { status: 'built' | 'failed' | 'quarantined'; toolName?: string; versionHash?: string; failureReason?: string; at?: number },
): boolean {
  const idea = existing.find((e) => e.id === id);
  if (!idea) return false;
  idea.status = outcome.status;
  if (outcome.status === 'built') {
    idea.builtTool = outcome.toolName;
    idea.builtVersionHash = outcome.versionHash;
    idea.builtAt = outcome.at ?? Date.now();
  } else {
    idea.failureReason = outcome.failureReason;
  }
  return true;
}

/** True when the card was finally consumed (built); such ids may be retried if the source re-posts with the SAME ternary contract. */
export function isBuilt(existing: ExternalStateIdea[], toolName: string): boolean {
  return existing.some((e) => e.status === 'built' && e.toolName === toolName);
}

export function summarizeIdeas(existing: ExternalStateIdea[]): { total: number; pending: number; built: number; failed: number; quarantined: number } {
  const s = { total: existing.length, pending: 0, built: 0, failed: 0, quarantined: 0 };
  for (const e of existing) s[e.status as keyof typeof s] += 1;
  return s;
}
